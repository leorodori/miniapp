## 9. 今後の展望
### タグ機能
フォルダとは異なる切り口で言葉を整理できる機能。
### 今日の言葉機能
過去の言葉との偶然の再会を生み出す機能。
### 通知機能
登録した言葉を定期的に振り返るためのリマインド機能。
